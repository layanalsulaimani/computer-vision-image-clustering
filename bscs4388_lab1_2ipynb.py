from sklearn.datasets import make_circles
from sklearn.cluster import SpectralClustering, spectral_clustering
from sklearn.feature_extraction import image
from skimage.transform import rescale
from skimage.filters import gaussian

points, groups = make_circles(
    n_samples=1000,
    factor=0.5,
    noise=0.05,
    random_state=42
)

plt.figure(figsize=(6, 6))
plt.scatter(points[:, 0], points[:, 1], color='gray', s=10)
plt.title("Data Before Spectral Clustering")
plt.savefig("spectral_data_before.png")
plt.show()

spectral_model = SpectralClustering(
    n_clusters=2,
    affinity='nearest_neighbors',
    random_state=42
)

circle_labels = spectral_model.fit_predict(points)

plt.figure(figsize=(6, 6))
plt.scatter(points[:, 0], points[:, 1], c=circle_labels, cmap='coolwarm', s=10)
plt.title("Data After Spectral Clustering")
plt.savefig("spectral_data_after.png")
plt.show()

coins = data.coins()

plt.imshow(coins, cmap='gray')
plt.title("Coins Image Before Spectral Clustering")
plt.axis('off')
plt.savefig("spectral_image_before.png")
plt.show()

smooth_coins = gaussian(coins, sigma=2)
small_coins = rescale(smooth_coins, 0.2)

coins_graph = image.img_to_graph(small_coins)

coins_graph.data = np.exp(-10 * coins_graph.data / coins_graph.data.std())

coins_labels = spectral_clustering(
    coins_graph,
    n_clusters=25,
    assign_labels='discretize',
    random_state=42
)

clustered_coins = coins_labels.reshape(small_coins.shape)

plt.imshow(clustered_coins, cmap='nipy_spectral')
plt.title("Coins Image After Spectral Clustering")
plt.axis('off')
plt.savefig("spectral_image_after.png")
plt.show()

